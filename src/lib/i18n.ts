const dictionaries = { en, vi } as const;

export function translate(lang: "en" | "vi", key: I18nKey): string {
  return (lang === "vi" ? vi[key] : undefined) ?? en[key];
}

export function useT() {
  const lang = useSettings((s) => s.settings?.general.language ?? "en");
  return (key: I18nKey, vars?: Record<string, string | number>) => {
    let out = translate(lang, key);
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
    return out;
  };
}

export { dictionaries };
